export function buildAutomationPresetRequest(preset: AutomationPromptPreset): string {
  return [
    `请创建一个名为「${preset.title}」的自动化任务，只创建配置，不立即执行任务。`,
    preset.scheduleEnabled
      ? `启用定时，使用本机时区，Cron 为 ${preset.cron}（分钟 小时 日 月 星期）。`
      : '不启用定时，创建后由我手动运行。',
    '请完整保留以下任务范围、检查清单、执行边界和验证要求：',
    '',
    preset.prompt,
  ].join('\n');
}
